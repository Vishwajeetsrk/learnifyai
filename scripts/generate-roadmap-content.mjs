import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const SRC = process.env.ROADMAP_SRC || "C:/Users/vishw/Music/developer-roadmap-master/developer-roadmap-master/roadmaps";
const OUT = join(dirname(fileURLToPath(import.meta.url)), "../src/lib/roadmap-content.generated.ts");

const SKIP_KINDS = new Set(["feed", "community", "podcast", "course"]);
const MAX_TOPICS = 30;
const MAX_RESOURCES = 4;

function readMdFile(p) {
  const raw = readFileSync(p, "utf8").replace(/^\uFEFF/, "");
  const lines = raw.split(/\r?\n/);
  const title = (lines[0] || "").replace(/^#+\s*/, "").trim() || "";
  const resources = [];
  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;
    const linkMatch = line.match(/^-\s*\[@(\w+)@([^\]]*)\]\((https?:\/\/[^)]+)\)$/i);
    if (linkMatch) {
      const kind = linkMatch[1].toLowerCase();
      if (SKIP_KINDS.has(kind)) continue;
      resources.push({ kind, title: linkMatch[2].trim(), url: linkMatch[3] });
    }
  }
  return { title, resources: resources.slice(0, MAX_RESOURCES) };
}

const roadmaps = readdirSync(SRC, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

const out = { generatedAt: new Date().toISOString().slice(0, 10), roadmaps: {} };

for (const id of roadmaps) {
  const dir = join(SRC, id);
  const contentDir = join(dir, "content");
  if (!existsSync(contentDir)) continue;
  const files = readdirSync(contentDir).filter((f) => f.endsWith(".md"));
  const topics = files
    .map((f) => {
      const parsed = readMdFile(join(contentDir, f));
      return parsed.title && parsed.resources.length ? { ...parsed, slug: f.replace(/\.md$/, "") } : null;
    })
    .filter(Boolean)
    .sort((a, b) => a.title.localeCompare(b.title))
    .slice(0, MAX_TOPICS);
  if (topics.length) out.roadmaps[id] = { name: id.replace(/-/g, " "), topics };
}

const ts =
  `// AUTO-GENERATED by scripts/generate-roadmap-content.mjs — DO NOT EDIT.\n` +
  `// Derived from the local roadmap.sh dataset (${Object.keys(out.roadmaps).length} roadmaps).\n\n` +
  `export interface RoadmapTopicResource { kind: string; title: string; url: string }\n` +
  `export interface RoadmapTopic { title: string; resources: RoadmapTopicResource[]; slug: string }\n` +
  `export const ROADMAP_CONTENT: Record<string, { name: string; topics: RoadmapTopic[] }> = ${JSON.stringify(out.roadmaps)};\n`;

writeFileSync(OUT, ts);
console.log(`Wrote ${OUT}`);
console.log(`Roadmaps: ${Object.keys(out.roadmaps).length}, topics: ${Object.values(out.roadmaps).reduce((s, r) => s + r.topics.length, 0)}`);
const kb = Math.round(statSync(OUT).size / 1024);
console.log(`Size: ${kb} KB`);
