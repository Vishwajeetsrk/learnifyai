/**
 * Detect social platform from a raw URL or handle.
 */
export function detectSocialPlatform(url: string): string {
  if (!url) return "website";
  const lower = url.trim().toLowerCase();

  if (lower.startsWith("mailto:") || lower.includes("@") && !lower.includes("/")) return "email";
  if (lower.includes("github.com") || lower.includes("github.io")) return "github";
  if (lower.includes("linkedin.com")) return "linkedin";
  if (lower.includes("twitter.com") || lower.includes("x.com")) return "x";
  if (lower.includes("instagram.com")) return "instagram";
  if (lower.includes("youtube.com") || lower.includes("youtu.be")) return "youtube";
  if (lower.includes("discord.gg") || lower.includes("discord.com")) return "discord";
  if (lower.includes("t.me") || lower.includes("telegram.me")) return "telegram";

  return "website";
}

/**
 * Validate and clean URL, preventing javascript: pseudo-protocols.
 */
export function normalizeSocialUrl(platform: string, input: string): string {
  if (!input) return "";
  const trimmed = input.trim();

  // Security guard against XSS protocols
  if (/^javascript:/i.test(trimmed) || /^data:/i.test(trimmed) || /^vbscript:/i.test(trimmed)) {
    return "#";
  }

  if (platform === "email" || trimmed.includes("@") && !trimmed.includes("/")) {
    return trimmed.startsWith("mailto:") ? trimmed : `mailto:${trimmed}`;
  }

  if (!/^https?:\/\//i.test(trimmed)) {
    return `https://${trimmed}`;
  }

  return trimmed;
}

export function getSocialPlatformInfo(platformOrUrl: string): SocialPlatformInfo {
  const platform = SOCIAL_REGISTRY[platformOrUrl.toLowerCase()]
    ? platformOrUrl.toLowerCase()
    : detectSocialPlatform(platformOrUrl);

  return SOCIAL_REGISTRY[platform] || SOCIAL_REGISTRY.website;
}

export function getSocialPlatformSvg(platformOrUrl: string, size = 16): string {
  const info = getSocialPlatformInfo(platformOrUrl);
  return `<span style="display:inline-flex;width:${size}px;height:${size}px;align-items:center;justify-content:center;flex-shrink:0;">${info.svg}</span>`;
}
